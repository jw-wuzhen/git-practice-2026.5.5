# 一个简单的Python示例程序，用于Git版本管理实践

def greet(name):
    """向指定用户打招呼"""
    return f"Hello, {name}! Welcome to Git practice."

def add(a, b):
    """两数相加"""
    return a + b

def main():
    print(greet("World"))
    print(greet("Git Learner"))
    print(f"1 + 2 = {add(1, 2)}")

if __name__ == "__main__":
    main()
